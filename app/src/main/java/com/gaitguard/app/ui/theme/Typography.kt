package com.gaitguard.app.ui.theme

import androidx.compose.material3.Typography
import androidx.compose.ui.text.TextStyle
import androidx.compose.ui.text.font.FontFamily
import androidx.compose.ui.text.font.FontStyle
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.text.googlefonts.Font
import androidx.compose.ui.text.googlefonts.GoogleFont
import androidx.compose.ui.unit.sp
import com.gaitguard.app.R

// ════════════════════════════════════════════════════════════════
//  Inter + Lexend via the Google Fonts content provider.
//  Setup:
//    1. Add this dependency in app/build.gradle.kts:
//         implementation("androidx.compose.ui:ui-text-google-fonts:1.6.7")
//    2. Add the certs resource in app/src/main/res/values/preloaded_fonts.xml:
//         (auto-generated by Android Studio when you add a downloadable font;
//          alternatively, drop the snippet from preloaded_fonts.xml in this folder)
//    3. Ensure your `R.array.com_google_android_gms_fonts_certs` resource exists
//       (Android Studio creates it when you add the first downloadable font from
//       the Resource Manager > Add font > Downloadable font dialog).
//
//  If you can't add the dependency right now, swap the families below with
//      val InterFamily = FontFamily.SansSerif
//      val LexendFamily = FontFamily.SansSerif
//  and everything keeps working — just without the custom faces.
// ════════════════════════════════════════════════════════════════

private val fontProvider = GoogleFont.Provider(
    providerAuthority = "com.google.android.gms.fonts",
    providerPackage   = "com.google.android.gms",
    certificates      = R.array.com_google_android_gms_fonts_certs
)

private val InterGF  = GoogleFont("Inter")
private val LexendGF = GoogleFont("Lexend")

val InterFamily = FontFamily(
    Font(googleFont = InterGF, fontProvider = fontProvider, weight = FontWeight.Normal),
    Font(googleFont = InterGF, fontProvider = fontProvider, weight = FontWeight.Medium),
    Font(googleFont = InterGF, fontProvider = fontProvider, weight = FontWeight.SemiBold),
    Font(googleFont = InterGF, fontProvider = fontProvider, weight = FontWeight.Bold),
    Font(googleFont = InterGF, fontProvider = fontProvider, weight = FontWeight.ExtraBold),
)

val LexendFamily = FontFamily(
    Font(googleFont = LexendGF, fontProvider = fontProvider, weight = FontWeight.Medium),
    Font(googleFont = LexendGF, fontProvider = fontProvider, weight = FontWeight.SemiBold),
    Font(googleFont = LexendGF, fontProvider = fontProvider, weight = FontWeight.Bold),
)

// ── Display data ─ big metric numerals
val DisplayDataStyle = TextStyle(
    fontFamily = LexendFamily,
    fontWeight = FontWeight.SemiBold,
    fontSize   = 48.sp,
    lineHeight = 52.sp,
    letterSpacing = (-0.96).sp
)

// ── Headlines
val HeadlineLgStyle = TextStyle(
    fontFamily = InterFamily,
    fontWeight = FontWeight.ExtraBold,
    fontSize   = 28.sp,
    lineHeight = 32.sp,
    letterSpacing = (-0.56).sp
)
val HeadlineMdStyle = TextStyle(
    fontFamily = InterFamily,
    fontWeight = FontWeight.Bold,
    fontSize   = 20.sp,
    lineHeight = 25.sp,
    letterSpacing = (-0.20).sp
)

// ── Title (card titles, list rows)
val TitleStyle = TextStyle(
    fontFamily = InterFamily,
    fontWeight = FontWeight.SemiBold,
    fontSize   = 14.sp,
    lineHeight = 19.sp
)

// ── Body
val BodyLgStyle = TextStyle(
    fontFamily = InterFamily,
    fontWeight = FontWeight.Normal,
    fontSize   = 14.sp,
    lineHeight = 21.sp
)
val BodySmStyle = TextStyle(
    fontFamily = InterFamily,
    fontWeight = FontWeight.Normal,
    fontSize   = 12.sp,
    lineHeight = 17.sp
)

// ── Label uppercase (pills, axis labels, micro headers)
val LabelCapsStyle = TextStyle(
    fontFamily = InterFamily,
    fontWeight = FontWeight.Bold,
    fontSize   = 10.5.sp,
    lineHeight = 12.sp,
    letterSpacing = 1.4.sp
)

// ── Metric label (small numbers in chips)
val MetricLabelStyle = TextStyle(
    fontFamily = LexendFamily,
    fontWeight = FontWeight.SemiBold,
    fontSize   = 18.sp,
    lineHeight = 20.sp,
    letterSpacing = (-0.36).sp
)

val GaitGuardTypography = Typography(
    displayLarge   = DisplayDataStyle,
    displayMedium  = DisplayDataStyle.copy(fontSize = 36.sp, lineHeight = 40.sp),
    headlineLarge  = HeadlineLgStyle,
    headlineMedium = HeadlineMdStyle,
    titleMedium    = TitleStyle,
    bodyLarge      = BodyLgStyle,
    bodyMedium     = BodyLgStyle,
    bodySmall      = BodySmStyle,
    labelLarge     = TitleStyle,
    labelMedium    = MetricLabelStyle,
    labelSmall     = LabelCapsStyle,
)
